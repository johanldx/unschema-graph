export const builders = builderGroups.flatMap((group) =>
  group.builders.map((builder) => ({
    ...builder,
    group: group.id,
    groupLabel: group.label,
    groupLabelFr: group.labelFr,
    schema: builder.schema ?? `${builder.name}Schema`,
    schemaType: builder.schemaType ?? builder.name,
    documentation: {
      schemaOrg: `https://schema.org/${builder.schemaType ?? builder.name}`,
      google: googleGuides[builder.schemaType ?? builder.name],
      related: group.builders
        .filter((candidate) => candidate.name !== builder.name)
        .slice(0, 4)
        .map((candidate) => candidate.name),
      commonErrors,
      imports: {
        astro: `import { ${builder.name} } from '@unschema-graph/astro';`,
        svelte: `import { ${builder.name} } from '@unschema-graph/svelte';`,
        core: `import { ${builder.name} } from '@unschema-graph/core';`,
      },
    },
  }))
);
